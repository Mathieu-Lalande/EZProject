-- V6 : temps passés et budget, capacité (absences, affectations), calendrier des jours fériés.

ALTER TABLE app_user ADD COLUMN capacity_days_per_week NUMERIC(3, 1) DEFAULT 5 NOT NULL;
ALTER TABLE organization ADD COLUMN holiday_calendar VARCHAR(10) DEFAULT 'FR' NOT NULL;

CREATE TABLE time_entry (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT        NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    task_id    BIGINT REFERENCES task (id) ON DELETE SET NULL,
    user_id    BIGINT        NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    work_date  DATE          NOT NULL,
    days       NUMERIC(5, 3) NOT NULL,
    comment    VARCHAR(300),
    created_at TIMESTAMP     NOT NULL
);
CREATE INDEX idx_time_project_date ON time_entry (project_id, work_date);
CREATE INDEX idx_time_user_date ON time_entry (user_id, work_date);

CREATE TABLE absence (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    start_date DATE         NOT NULL,
    end_date   DATE         NOT NULL,
    kind       VARCHAR(20)  NOT NULL,
    comment    VARCHAR(200),
    created_at TIMESTAMP    NOT NULL
);
CREATE INDEX idx_absence_user ON absence (user_id, start_date);

CREATE TABLE allocation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT        NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    user_id       BIGINT        NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    start_date    DATE          NOT NULL,
    end_date      DATE          NOT NULL,
    days_per_week NUMERIC(3, 1) NOT NULL,
    created_at    TIMESTAMP     NOT NULL
);
CREATE INDEX idx_allocation_user ON allocation (user_id, start_date);
CREATE INDEX idx_allocation_project ON allocation (project_id);


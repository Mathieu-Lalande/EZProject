-- V5 : cycle de vie des comptes (désactivation, mot de passe à changer, anonymisation RGPD) et journal d'audit.

ALTER TABLE app_user ADD COLUMN active BOOLEAN DEFAULT TRUE NOT NULL;
ALTER TABLE app_user ADD COLUMN must_change_password BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE app_user ADD COLUMN deleted_at TIMESTAMP;

CREATE TABLE audit_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT       NOT NULL REFERENCES organization (id) ON DELETE CASCADE,
    actor_id        BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    actor_name      VARCHAR(120),
    action          VARCHAR(60)  NOT NULL,
    entity_type     VARCHAR(40),
    entity_id       BIGINT,
    summary         VARCHAR(500),
    created_at      TIMESTAMP    NOT NULL
);
CREATE INDEX idx_audit_org_date ON audit_event (organization_id, created_at);

-- V9 : double authentification TOTP (secret chiffré, anti-rejeu) et codes de secours hachés.

ALTER TABLE app_user ADD COLUMN mfa_secret VARCHAR(255);
ALTER TABLE app_user ADD COLUMN mfa_enabled BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE app_user ADD COLUMN mfa_last_step BIGINT;

CREATE TABLE mfa_recovery_code (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    code_hash VARCHAR(255) NOT NULL,
    used_at   TIMESTAMP
);
CREATE INDEX idx_recovery_user ON mfa_recovery_code (user_id);

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    display_name  VARCHAR(120) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    job_title     VARCHAR(120),
    created_at    TIMESTAMP    NOT NULL
);

CREATE TABLE project (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(12)   NOT NULL UNIQUE,
    name        VARCHAR(150)  NOT NULL,
    description VARCHAR(4000),
    client      VARCHAR(150),
    type        VARCHAR(20)   NOT NULL,
    status      VARCHAR(20)   NOT NULL,
    health      VARCHAR(10)   NOT NULL,
    color       VARCHAR(20)   NOT NULL,
    owner_id    BIGINT REFERENCES app_user (id),
    start_date  DATE,
    end_date    DATE,
    budget_days INTEGER,
    created_at  TIMESTAMP     NOT NULL,
    updated_at  TIMESTAMP     NOT NULL
);

CREATE TABLE project_module (
    project_id BIGINT      NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    module     VARCHAR(30) NOT NULL,
    PRIMARY KEY (project_id, module)
);

CREATE TABLE task (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT        NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    title        VARCHAR(200)  NOT NULL,
    description  VARCHAR(4000),
    status       VARCHAR(20)   NOT NULL,
    priority     VARCHAR(10)   NOT NULL,
    assignee_id  BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    story_points INTEGER,
    due_date     DATE,
    position     INTEGER       NOT NULL,
    created_at   TIMESTAMP     NOT NULL,
    completed_at TIMESTAMP
);
CREATE INDEX idx_task_project ON task (project_id);
CREATE INDEX idx_task_assignee ON task (assignee_id);

CREATE TABLE todo_item (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    project_id BIGINT REFERENCES project (id) ON DELETE CASCADE,
    title      VARCHAR(300) NOT NULL,
    done       BOOLEAN      NOT NULL,
    due_date   DATE,
    created_at TIMESTAMP    NOT NULL
);
CREATE INDEX idx_todo_owner ON todo_item (owner_id);

CREATE TABLE retro_phase (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT       NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    name          VARCHAR(150) NOT NULL,
    kind          VARCHAR(20)  NOT NULL,
    duration_days INTEGER      NOT NULL,
    sort_order    INTEGER      NOT NULL,
    done          BOOLEAN      NOT NULL
);
CREATE INDEX idx_retro_project ON retro_phase (project_id);

CREATE TABLE poker_round (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id     BIGINT       NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    task_id        BIGINT REFERENCES task (id) ON DELETE SET NULL,
    story_title    VARCHAR(200) NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    final_estimate VARCHAR(10),
    created_at     TIMESTAMP    NOT NULL
);

CREATE TABLE poker_vote (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_id BIGINT      NOT NULL REFERENCES poker_round (id) ON DELETE CASCADE,
    voter_id BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    card     VARCHAR(10) NOT NULL,
    CONSTRAINT uk_vote_round_voter UNIQUE (round_id, voter_id)
);

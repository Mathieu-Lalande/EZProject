-- V7 : registre des risques et des décisions, météo projet historisée (rapports d'avancement).

CREATE TABLE risk (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT        NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    title       VARCHAR(200)  NOT NULL,
    description VARCHAR(2000),
    probability INTEGER       NOT NULL,
    impact      INTEGER       NOT NULL,
    status      VARCHAR(20)   NOT NULL,
    owner_id    BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    mitigation  VARCHAR(2000),
    due_date    DATE,
    created_at  TIMESTAMP     NOT NULL,
    updated_at  TIMESTAMP     NOT NULL
);
CREATE INDEX idx_risk_project ON risk (project_id);

CREATE TABLE decision (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT        NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    title         VARCHAR(200)  NOT NULL,
    description   VARCHAR(2000),
    decided_on    DATE,
    decided_by    VARCHAR(150),
    status        VARCHAR(20)   NOT NULL,
    created_by_id BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    created_at    TIMESTAMP     NOT NULL
);
CREATE INDEX idx_decision_project ON decision (project_id);

CREATE TABLE status_report (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       BIGINT        NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    author_id        BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    report_date      DATE          NOT NULL,
    health           VARCHAR(10)   NOT NULL,
    trend            VARCHAR(10)   NOT NULL,
    summary          VARCHAR(2000) NOT NULL,
    achievements     VARCHAR(2000),
    next_steps       VARCHAR(2000),
    attention_points VARCHAR(2000),
    created_at       TIMESTAMP     NOT NULL
);
CREATE INDEX idx_report_project_date ON status_report (project_id, report_date);


-- V2 : passage en SaaS multi-organisation (multi-tenant).
-- Les données existantes sont conservées et rattachées à une organisation par défaut.
-- =====================================================================

CREATE TABLE organization (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(150) NOT NULL,
    slug               VARCHAR(60)  NOT NULL UNIQUE,
    plan               VARCHAR(20)  NOT NULL,
    custom_permissions BOOLEAN      DEFAULT FALSE NOT NULL,
    created_at         TIMESTAMP    NOT NULL
);

INSERT INTO organization (name, slug, plan, custom_permissions, created_at)
VALUES ('Mon organisation', 'default', 'TEAM', FALSE, CURRENT_TIMESTAMP);

-- ---------- Utilisateurs : rattachement à une organisation ----------
ALTER TABLE app_user ADD COLUMN organization_id BIGINT;
UPDATE app_user SET organization_id = (SELECT id FROM organization WHERE slug = 'default');
ALTER TABLE app_user ALTER COLUMN organization_id SET NOT NULL;
ALTER TABLE app_user ADD CONSTRAINT fk_user_org FOREIGN KEY (organization_id) REFERENCES organization (id);
CREATE INDEX idx_user_org ON app_user (organization_id);
-- Le premier administrateur devient propriétaire de l'organisation
UPDATE app_user SET role = 'OWNER' WHERE id = (SELECT MIN(id) FROM app_user WHERE role = 'ADMIN');

-- ---------- Équipes ----------
CREATE TABLE team (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT       NOT NULL REFERENCES organization (id) ON DELETE CASCADE,
    name            VARCHAR(100) NOT NULL,
    description     VARCHAR(500),
    color           VARCHAR(20)  NOT NULL,
    created_at      TIMESTAMP    NOT NULL,
    CONSTRAINT uk_team_org_name UNIQUE (organization_id, name)
);

CREATE TABLE team_member (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT      NOT NULL REFERENCES team (id) ON DELETE CASCADE,
    user_id BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    role    VARCHAR(20) NOT NULL,
    CONSTRAINT uk_team_member UNIQUE (team_id, user_id)
);
CREATE INDEX idx_team_member_user ON team_member (user_id);

INSERT INTO team (organization_id, name, color, created_at)
SELECT id, 'Équipe principale', '#6366f1', CURRENT_TIMESTAMP FROM organization WHERE slug = 'default';

INSERT INTO team_member (team_id, user_id, role)
SELECT t.id, u.id, CASE WHEN u.role IN ('OWNER', 'ADMIN', 'MANAGER') THEN 'LEAD' ELSE 'CONTRIBUTOR' END
FROM team t JOIN app_user u ON u.organization_id = t.organization_id;

-- ---------- Projets : organisation, équipe, visibilité, priorité ----------
ALTER TABLE project ADD COLUMN organization_id BIGINT;
ALTER TABLE project ADD COLUMN team_id BIGINT;
ALTER TABLE project ADD COLUMN visibility VARCHAR(20) DEFAULT 'ORGANIZATION' NOT NULL;
ALTER TABLE project ADD COLUMN priority VARCHAR(10) DEFAULT 'P3' NOT NULL;
ALTER TABLE project ADD COLUMN status_reason VARCHAR(500);
UPDATE project SET organization_id = (SELECT id FROM organization WHERE slug = 'default'),
                   team_id = (SELECT MIN(id) FROM team);
ALTER TABLE project ALTER COLUMN organization_id SET NOT NULL;
ALTER TABLE project ADD CONSTRAINT fk_project_org FOREIGN KEY (organization_id) REFERENCES organization (id) ON DELETE CASCADE;
ALTER TABLE project ADD CONSTRAINT fk_project_team FOREIGN KEY (team_id) REFERENCES team (id) ON DELETE SET NULL;
CREATE INDEX idx_project_org ON project (organization_id);
CREATE INDEX idx_project_team ON project (team_id);

-- ---------- Membres explicites d'un projet (transverses, invités) ----------
CREATE TABLE project_member (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT      NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    role       VARCHAR(20) NOT NULL,
    CONSTRAINT uk_project_member UNIQUE (project_id, user_id)
);
CREATE INDEX idx_project_member_user ON project_member (user_id);

-- ---------- Matrice rôles / permissions personnalisable par organisation ----------
CREATE TABLE role_permission (
    organization_id BIGINT      NOT NULL REFERENCES organization (id) ON DELETE CASCADE,
    role            VARCHAR(20) NOT NULL,
    permission      VARCHAR(40) NOT NULL,
    PRIMARY KEY (organization_id, role, permission)
);

-- ---------- Journal des changements de statut ----------
CREATE TABLE project_status_change (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT      NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    from_status   VARCHAR(20),
    to_status     VARCHAR(20) NOT NULL,
    reason        VARCHAR(500),
    changed_by_id BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    changed_at    TIMESTAMP   NOT NULL
);
CREATE INDEX idx_status_change_project ON project_status_change (project_id);

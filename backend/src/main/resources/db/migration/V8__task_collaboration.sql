-- V8 : collaboration sur les tâches : commentaires, sous-tâches (checklist), étiquettes, pièces jointes.

CREATE TABLE task_comment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    BIGINT        NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    author_id  BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    body       VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP     NOT NULL,
    edited_at  TIMESTAMP
);
CREATE INDEX idx_comment_task ON task_comment (task_id);

CREATE TABLE task_checklist_item (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id  BIGINT       NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    title    VARCHAR(300) NOT NULL,
    done     BOOLEAN      NOT NULL,
    position INTEGER      NOT NULL
);
CREATE INDEX idx_checklist_task ON task_checklist_item (task_id);

CREATE TABLE task_label (
    task_id BIGINT      NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    label   VARCHAR(30) NOT NULL,
    PRIMARY KEY (task_id, label)
);

-- Contenu binaire stocké en base (BYTEA : PostgreSQL ; alias de VARBINARY sous H2)
CREATE TABLE task_attachment (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id      BIGINT       NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    uploader_id  BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    filename     VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size_bytes   BIGINT       NOT NULL,
    content      BYTEA,
    created_at   TIMESTAMP    NOT NULL
);
CREATE INDEX idx_attachment_task ON task_attachment (task_id);
